package com.burhannexus.dukaandost.data.pdf

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import com.burhannexus.dukaandost.core.Money
import com.burhannexus.dukaandost.domain.model.BusinessProfile
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.math.BigDecimal
import java.time.Instant
import java.time.ZoneId
import java.time.format.DateTimeFormatter
import javax.inject.Inject
import javax.inject.Singleton

/** One printed line of a statement; the description is already in the user's language. */
data class StatementRow(
    /** 0 = no date (the opening balance). */
    val createdAt: Long,
    val description: String,
    val increase: BigDecimal,
    val decrease: BigDecimal,
    val balance: BigDecimal
)

data class StatementLabels(
    val title: String,
    val partyName: String,
    val partyPhone: String?,
    val phoneLabel: String,
    val dateColumn: String,
    val descriptionColumn: String,
    val increaseColumn: String,
    val decreaseColumn: String,
    val balanceColumn: String,
    /** e.g. "Balance to receive: Rs. 1,200.00" */
    val closingText: String,
    val printedOn: String
)

/** A5 account statement (ledger) with the shop's logo, name, address and phone on top. */
@Singleton
class StatementPdfGenerator @Inject constructor(
    @ApplicationContext private val context: Context
) {
    suspend fun generate(
        rows: List<StatementRow>,
        profile: BusinessProfile?,
        logoPng: ByteArray?,
        labels: StatementLabels
    ): File = withContext(Dispatchers.IO) {
        val directory = File(context.cacheDir, "receipts").apply { mkdirs() }
        val safeName = labels.partyName.replace(Regex("[^A-Za-z0-9_-]"), "_").take(30).ifEmpty { "party" }
        val file = File(directory, "Statement-$safeName.pdf")
        val document = PdfDocument()
        try {
            StatementDrawer(document, rows, profile, logoPng, labels).draw()
            file.outputStream().use { document.writeTo(it) }
        } finally {
            document.close()
        }
        file
    }
}

private const val W = 420
private const val H = 595
private const val M = 28f
private const val RIGHT_EDGE = W - M
private const val DATE_X = M
private const val DESC_X = 84f
private const val INC_RIGHT = 262f
private const val DEC_RIGHT = 328f

private class StatementDrawer(
    private val document: PdfDocument,
    private val rows: List<StatementRow>,
    private val profile: BusinessProfile?,
    private val logoPng: ByteArray?,
    private val labels: StatementLabels
) {
    private val dateFormat = DateTimeFormatter.ofPattern("dd MMM yy")
    private val regular = Paint(Paint.ANTI_ALIAS_FLAG).apply { textSize = 8.5f; color = Color.BLACK }
    private val small = Paint(regular).apply { textSize = 8f; color = Color.DKGRAY }
    private val bold = Paint(regular).apply { typeface = Typeface.DEFAULT_BOLD }
    private val title = Paint(bold).apply { textSize = 12f }
    private val shop = Paint(bold).apply { textSize = 16f }
    private val line = Paint().apply { color = Color.GRAY; strokeWidth = 0.7f }

    private var pageNumber = 0
    private lateinit var page: PdfDocument.Page
    private lateinit var canvas: Canvas
    private var y = M

    fun draw() {
        startPage()
        drawBusinessHeader()
        canvas.drawText(labels.title, M, y, title)
        val printed = labels.printedOn
        canvas.drawText(printed, RIGHT_EDGE - regular.measureText(printed), y, regular)
        y += 14f
        canvas.drawText(labels.partyName, M, y, bold)
        y += 11f
        labels.partyPhone?.takeIf { it.isNotBlank() }?.let {
            canvas.drawText("${labels.phoneLabel}: $it", M, y, regular)
            y += 11f
        }
        y += 6f
        drawTableHeader()
        rows.forEach { drawRow(it) }
        ensure(40f)
        canvas.drawLine(M, y, RIGHT_EDGE, y, line)
        y += 16f
        canvas.drawText(labels.closingText, M, y, title)
        y += 22f
        val note = profile?.footerNote.orEmpty()
        if (note.isNotBlank()) {
            canvas.drawText(fit(note, regular, RIGHT_EDGE - M), M, y, regular)
            y += 12f
        }
        val brand = "Generated by Dukaan Dost"
        canvas.drawText(brand, (W - small.measureText(brand)) / 2f, y + 4f, small)
        document.finishPage(page)
    }

    private fun startPage() {
        pageNumber++
        page = document.startPage(PdfDocument.PageInfo.Builder(W, H, pageNumber).create())
        canvas = page.canvas
        y = M
    }

    private fun ensure(height: Float) {
        if (y + height <= H - M) return
        document.finishPage(page)
        startPage()
        canvas.drawText("${labels.partyName} ($pageNumber)", M, y + 9f, bold)
        y += 22f
        drawTableHeader()
    }

    private fun drawBusinessHeader() {
        val logo = logoPng?.let { BitmapFactory.decodeByteArray(it, 0, it.size) }?.let { scaled(it, 50) }
        var textX = M
        if (logo != null) {
            canvas.drawBitmap(logo, M, y, null)
            textX = M + logo.width + 10f
        }
        val width = RIGHT_EDGE - textX
        var textY = y + 14f
        val name = profile?.shopName?.ifBlank { null } ?: "Dukaan Dost"
        canvas.drawText(fit(name, shop, width), textX, textY, shop)
        textY += 18f
        profile?.address?.takeIf { it.isNotBlank() }?.let {
            canvas.drawText(fit(it, regular, width), textX, textY, regular)
            textY += 11f
        }
        profile?.phone?.takeIf { it.isNotBlank() }?.let {
            canvas.drawText("${labels.phoneLabel}: $it", textX, textY, regular)
            textY += 11f
        }
        y = maxOf(textY, y + (logo?.height ?: 0)) + 6f
        canvas.drawLine(M, y, RIGHT_EDGE, y, line)
        y += 16f
    }

    private fun drawTableHeader() {
        canvas.drawText(labels.dateColumn, DATE_X, y, bold)
        canvas.drawText(labels.descriptionColumn, DESC_X, y, bold)
        right(labels.increaseColumn, INC_RIGHT, bold)
        right(labels.decreaseColumn, DEC_RIGHT, bold)
        right(labels.balanceColumn, RIGHT_EDGE, bold)
        y += 4f
        canvas.drawLine(M, y, RIGHT_EDGE, y, line)
        y += 12f
    }

    private fun drawRow(row: StatementRow) {
        ensure(16f)
        if (row.createdAt != 0L) {
            val date = Instant.ofEpochMilli(row.createdAt).atZone(ZoneId.systemDefault()).format(dateFormat)
            canvas.drawText(date, DATE_X, y, regular)
        }
        canvas.drawText(fit(row.description, regular, INC_RIGHT - DESC_X - 52f), DESC_X, y, regular)
        if (row.increase.signum() > 0) right(Money.format(row.increase), INC_RIGHT, regular)
        if (row.decrease.signum() > 0) right(Money.format(row.decrease), DEC_RIGHT, regular)
        right(Money.format(row.balance), RIGHT_EDGE, regular)
        y += 14f
    }

    private fun right(text: String, rightX: Float, paint: Paint) {
        canvas.drawText(text, rightX - paint.measureText(text), y, paint)
    }

    private fun fit(text: String, paint: Paint, maxWidth: Float): String {
        if (paint.measureText(text) <= maxWidth) return text
        val ellipsis = "…"
        var end = text.length
        while (end > 0 && paint.measureText(text, 0, end) + paint.measureText(ellipsis) > maxWidth) end--
        return text.substring(0, end) + ellipsis
    }

    private fun scaled(bitmap: Bitmap, height: Int): Bitmap {
        if (bitmap.height <= 0) return bitmap
        val width = (bitmap.width * (height.toFloat() / bitmap.height)).toInt().coerceAtLeast(1)
        return Bitmap.createScaledBitmap(bitmap, width.coerceAtMost(120), height, true)
    }
}
