package com.burhannexus.dukaandost.domain.calc

import com.burhannexus.dukaandost.core.InvoiceNumbers
import com.burhannexus.dukaandost.core.Money
import com.burhannexus.dukaandost.domain.model.InvoiceDetail
import com.burhannexus.dukaandost.domain.model.InvoiceKind
import java.time.Instant
import java.time.ZoneId
import java.time.format.DateTimeFormatter

/** Plain-text invoice for sharing (WhatsApp, SMS...). PDF receipts come in the next step. */
object InvoiceTextFormatter {
    private val dateFormat = DateTimeFormatter.ofPattern("dd MMM yyyy, hh:mm a")

    /**
     * [businessLines] are the shop name, address and phone printed at the top;
     * when empty, the app name is used.
     */
    fun format(
        invoice: InvoiceDetail,
        title: String,
        partyLabel: String,
        businessLines: List<String> = emptyList()
    ): String {
        val number = if (invoice.kind == InvoiceKind.SALE) InvoiceNumbers.sale(invoice.number)
        else InvoiceNumbers.purchase(invoice.number)
        val date = Instant.ofEpochMilli(invoice.createdAt).atZone(ZoneId.systemDefault()).format(dateFormat)
        return buildString {
            if (businessLines.isEmpty()) appendLine("*Dukaan Dost*") else businessLines.forEach { appendLine(it) }
            appendLine("$title $number")
            appendLine(date)
            invoice.partyName?.let { appendLine("$partyLabel: $it") }
            appendLine("------------------------")
            invoice.lines.forEachIndexed { index, line ->
                appendLine("${index + 1}. ${line.name}")
                append("   ${line.quantity.stripTrailingZeros().toPlainString()} x ${Money.format(line.unitPrice)}")
                if (line.discount.signum() > 0) append(" (- ${Money.format(line.discount)})")
                appendLine(" = ${Money.format(line.total)}")
            }
            appendLine("------------------------")
            appendLine("Subtotal: ${Money.format(invoice.subtotal)}")
            if (invoice.invoiceDiscount.signum() > 0) appendLine("Discount: -${Money.format(invoice.invoiceDiscount)}")
            if (invoice.extraExpenses.signum() > 0) appendLine("Extra expenses: ${Money.format(invoice.extraExpenses)}")
            appendLine("*Total: ${Money.format(invoice.total)}*")
            appendLine("Paid: ${Money.format(invoice.paid)}")
            if (invoice.remaining.signum() > 0) appendLine("Remaining: ${Money.format(invoice.remaining)}")
            append("Generated by Dukaan Dost")
        }
    }
}
